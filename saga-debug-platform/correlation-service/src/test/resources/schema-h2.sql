-- Minimal H2 schema for the context-load test.
--
-- The scheduled detectors start as soon as the context refreshes and immediately
-- query these tables, so they have to exist or the test drowns in SQL errors that
-- hide a real wiring failure.
--
-- This mirrors the Flyway migrations in shape only. It is not a substitute for
-- running them: the real schema is Postgres (jsonb, TIMESTAMPTZ, the V7 indexes) and
-- only a Postgres instance verifies it.

CREATE TABLE saga_instances (
    saga_id       VARCHAR(300) PRIMARY KEY,
    source_name   VARCHAR(120) NOT NULL DEFAULT 'default',
    workflow_type VARCHAR(255) NOT NULL DEFAULT 'ORDER_SAGA',
    workflow_conflicts JSON NOT NULL DEFAULT '[]',
    order_id      VARCHAR(300),
    status        VARCHAR(20)  NOT NULL,
    start_time    TIMESTAMP WITH TIME ZONE NOT NULL,
    end_time      TIMESTAMP WITH TIME ZONE,
    last_updated  TIMESTAMP WITH TIME ZONE NOT NULL,
    version       BIGINT       NOT NULL DEFAULT 0
);

CREATE TABLE saga_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id     VARCHAR(300) NOT NULL,
    saga_id      VARCHAR(300) NOT NULL,
    source_name  VARCHAR(120) NOT NULL DEFAULT 'default',
    correlation_basis VARCHAR(32),
    event_type   VARCHAR(255) NOT NULL,
    step_name    VARCHAR(255),
    service_name VARCHAR(255),
    timestamp    TIMESTAMP WITH TIME ZONE NOT NULL,
    event_time_source VARCHAR(20) CHECK (event_time_source IN ('DECLARED', 'TRANSPORT')),
    payload      JSON         NOT NULL,
    received_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    causation_id   VARCHAR(300),
    span_id        VARCHAR(64),
    parent_span_id VARCHAR(64),
    trace_id       VARCHAR(64),
    transport_ref  VARCHAR(300),
    -- V13: an event id is unique within the system that issued it, not globally.
    CONSTRAINT saga_events_source_event_id_key UNIQUE (source_name, event_id)
);

CREATE TABLE anomalies (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    saga_id            VARCHAR(300) NOT NULL,
    anomaly_type       VARCHAR(50) NOT NULL,
    detected_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    description        CLOB,
    observed_value     CLOB,
    expected_value     CLOB,
    threshold_source   VARCHAR(120),
    evidence_event_ids JSON,
    measured_at        TIMESTAMP WITH TIME ZONE,
    retracted_at       TIMESTAMP WITH TIME ZONE,
    retraction_reason  CLOB
);

CREATE TABLE rca_results (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    saga_id             VARCHAR(300) NOT NULL,
    root_cause          VARCHAR(100),
    outcome             VARCHAR(30)  NOT NULL,
    severity            VARCHAR(20)  NOT NULL,
    confidence          DOUBLE,
    rule_id             VARCHAR(50),
    evidence            JSON         NOT NULL,
    suggestions         JSON,
    contributing_causes JSON,
    rca_status          VARCHAR(40)  NOT NULL,
    primary_root_causes JSON         NOT NULL,
    candidates          JSON         NOT NULL,
    missing_evidence    JSON         NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Mirrors V16. The scheduled sweeps take a lease before they run, so the context-load
-- test needs the table to exist or every tick logs a SQL error.
CREATE TABLE scheduler_lease (
    sweep            VARCHAR(64)  PRIMARY KEY,
    holder           VARCHAR(128) NOT NULL,
    token            VARCHAR(36)  NOT NULL,
    taken_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    lease_expires_at BIGINT       NOT NULL
);

-- Mirrors V11 as amended by V13: an alias belongs to the system that issued it.
CREATE TABLE execution_aliases (
    source_name        VARCHAR(120) NOT NULL,
    alias_key          VARCHAR(200) NOT NULL,
    execution_id       VARCHAR(300) NOT NULL,
    linked_by_event_id VARCHAR(200),
    observed_at        TIMESTAMP    NOT NULL,
    PRIMARY KEY (source_name, alias_key)
);

-- Mirrors V19 + V20 + V21: lifecycle facts from the container runtime or a pushed report.
CREATE TABLE service_lifecycle_events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_name  VARCHAR(255) NOT NULL,
    state         VARCHAR(16)  NOT NULL,
    occurred_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    received_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    source        VARCHAR(64)  NOT NULL,
    detail        VARCHAR(512),
    external_id   VARCHAR(255) NOT NULL,
    basis         VARCHAR(16)  NOT NULL DEFAULT 'PROCESS',
    scope         VARCHAR(255),
    CONSTRAINT uq_service_lifecycle_source_external UNIQUE (source, external_id)
);
